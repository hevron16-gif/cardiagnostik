    /// <summary>
    /// Возвращает коды, характерные для марки, или null (все).
    /// </summary>
    public static HashSet<string>? GetCodesForBrand(string brand)
    {
        if (string.IsNullOrEmpty(brand)) return null;
        if (BrandCodes.TryGetValue(brand, out var codes)) return codes;

        // Алиасы: LADA → ВАЗ, KAMAZ → КАМАЗ
        var normalized = DiagramDatabase.NormalizeBrand(brand);
        if (BrandCodes.TryGetValue(normalized, out codes)) return codes;
        return null;
    }
